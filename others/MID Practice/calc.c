#include<stdio.h>
int main(){
    int n1,n2;
    printf("Enter First No. -> ");
    scanf("%d",&n1);
    printf("Enter Second No. -> ");
    scanf("%d",&n2);
    printf("Sum = %d\n",n1+n2);
    printf("Difference = %d\n",n1-n2);
    printf("Product = %d\n",n1*n2);
    printf("Division = %d",n1/n2);
    return 0;
}

